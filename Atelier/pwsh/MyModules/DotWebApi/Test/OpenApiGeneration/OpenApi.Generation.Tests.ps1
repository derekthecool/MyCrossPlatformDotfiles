Describe 'New-OpenApiClient options' {
    It '-IncludePath / -ExcludePath filter operations by path wildcard' {
        $only = Invoke-Generator -Path $kokoroSpec -OutputPath (Join-Path $TestDrive 'v1only') -IncludePath '/v1/*', '/health'
        $only.Function | Should -Contain 'New-KokoroSpeech'
        $only.Function | Should -Contain 'Test-KokoroHealth'
        $only.Function | Should -Not -Contain 'New-KokoroDialogue'

        $trimmed = Invoke-Generator -Path $kokoroSpec -OutputPath (Join-Path $TestDrive 'trimmed') -ExcludePath '/dev/*', '/debug/*', '/web/*'
        $trimmed.Function | Should -Contain 'New-KokoroSpeech'
        $trimmed.Function | Should -Not -Contain 'New-KokoroDialogue'
        $trimmed.Function | Should -Not -Contain 'Get-KokoroSystemInfo'
        $trimmed.Function | Should -Not -Contain 'Get-KokoroWebConfig'
    }

    It '-Tag filters by operation tag' {
        $tagged = Invoke-Generator -Path $petSpec -OutputPath (Join-Path $TestDrive 'tag') -Tag 'pets'
        $tagged.Function | Should -Contain 'Get-PetStorePet'
        $tagged.Function | Should -Not -Contain 'Test-PetStoreHealth'
    }

    It 'skips deprecated operations unless -IncludeDeprecated' {
        $script:pet.Function | Should -Not -Contain 'Get-PetStoreOldThing'
        $withOld = Invoke-Generator -Path $petSpec -OutputPath (Join-Path $TestDrive 'old') -IncludeDeprecated
        $withOld.Function | Should -Contain 'Get-PetStoreOldThing'
    }

    It '-Name and -Prefix control the file and function names' {
        $custom = Invoke-Generator -Path $kokoroSpec -OutputPath (Join-Path $TestDrive 'custom') -Name Tts -Prefix Voice
        $custom.ClientPath | Should -BeLike '*Tts.ps1'
        $custom.Function | Should -Contain 'New-VoiceSpeech'
        $custom.Function | Should -Contain 'Set-VoiceDefaultEndpoint'
    }

    It 'accepts an explicit .ps1 output path in any directory' {
        $file = Join-Path $TestDrive 'elsewhere/deep/MyClient.ps1'
        $result = Invoke-Generator -Path $kokoroSpec -OutputPath $file
        $result.ClientPath | Should -Be $file
        $file | Should -Exist
    }

    It 'bakes -DefaultEndpoint into the client info and falls back to the spec server' {
        (Get-Content -LiteralPath $script:kokoro.ClientPath -Raw) | Should -Match "DefaultEndpoint = 'http://192.168.1.103:8880'"
        $petText = Get-Content -LiteralPath $script:pet.ClientPath -Raw
        $petText | Should -Match "DefaultEndpoint = \`$null"
        $petText | Should -Match "ServerUrl       = 'https://pets.example.com/api/v3'"
        $petText | Should -Match "BasePath        = '/api/v3'"
        $petText | Should -Match "Type = 'http'; Scheme = 'bearer'"
    }

    It 'chooses Module runtime inside DotWebApi and Embedded elsewhere' {
        $inside = Join-Path $moduleRoot 'Source/ZzWhatIfOnly'
        $result = Invoke-Generator -Path $kokoroSpec -OutputPath $inside -WhatIf
        $result.RuntimeMode | Should -Be 'Module'
        $result.RuntimePath | Should -BeNullOrEmpty
        $inside | Should -Not -Exist
        (Invoke-Generator -Path $kokoroSpec -OutputPath (Join-Path $TestDrive 'outside')).RuntimeMode | Should -Be 'Embedded'
    }

    It 'refuses to overwrite a hand-written file without -Force' {
        $file = Join-Path $TestDrive 'handwritten.ps1'
        Set-Content -LiteralPath $file -Value '# mine'
        { New-OpenApiClient -Path $kokoroSpec -OutputPath $file 6>$null } | Should -Throw '*not generated*'
        (Get-Content -LiteralPath $file -Raw).Trim() | Should -Be '# mine'
        $null = Invoke-Generator -Path $kokoroSpec -OutputPath $file -Force
        (Get-Content -LiteralPath $file -Raw) | Should -Match '# <auto-generated>'
    }

    It 'fails clearly when every operation is filtered out' {
        { New-OpenApiClient -Path $kokoroSpec -OutputPath (Join-Path $TestDrive 'none') -IncludePath '/nothing' 6>$null } | Should -Throw '*No operations*'
    }

    It 'generates from a Swagger 2.0 document' {
        $widgets = Invoke-Generator -Path (Join-Path $fixtures 'widgets.swagger2.json') -OutputPath (Join-Path $TestDrive 'widgets')
        $widgets.Function | Should -Contain 'New-WidgetWidget'
        $widgets.Function | Should -Contain 'Send-WidgetBlueprint'
    }

    It 'generates from the Kroger OpenAPI 3.0.3 documents' {
        foreach ($name in 'kroger_chain_location_openapi.json', 'kroger_cart_open_api.json', 'kroger_auth_openapi.json')
        {
            $result = Invoke-Generator -Path (Join-Path $moduleRoot "Source/Kroger/$name") -OutputPath (Join-Path $TestDrive "kroger/$name")
            $tokens = $null
            $errors = $null
            $null = [System.Management.Automation.Language.Parser]::ParseFile($result.ClientPath, [ref]$tokens, [ref]$errors)
            $errors | Should -BeNullOrEmpty -Because $name
        }
    }
}

Describe 'New-OpenApiClient -UpdateManifest' {
    BeforeEach {
        $script:mod = Join-Path $TestDrive "mod$([guid]::NewGuid().ToString('N').Substring(0, 6))"
        $null = New-Item -ItemType Directory -Path (Join-Path $script:mod 'Source/Kokoro') -Force
        Set-Content -LiteralPath (Join-Path $script:mod 'Other.psm1') -Value ''
        $script:psd1 = Join-Path $script:mod 'Other.psd1'
        Set-Content -LiteralPath $script:psd1 -Value "@{`n    RootModule = 'Other.psm1'`n    ModuleVersion = '1.0'`n    GUID = '22222222-2222-2222-2222-222222222222'`n    FunctionsToExport = @(`n        'Get-Existing'`n    )`n}`n"
    }

    It 'finds the nearest manifest above the output and writes a region' {
        $result = Invoke-Generator -Path $kokoroSpec -OutputPath (Join-Path $script:mod 'Source/Kokoro') -UpdateManifest
        $result.ManifestPath | Should -Be $script:psd1
        $data = Import-PowerShellDataFile -LiteralPath $script:psd1
        $data.FunctionsToExport | Should -Contain 'Get-Existing'
        $data.FunctionsToExport | Should -Contain 'New-KokoroSpeech'
        $data.FunctionsToExport.Count | Should -Be (1 + $result.Function.Count)
    }

    It 'uses an explicit -ManifestPath that is nowhere near the output' {
        $elsewhere = Join-Path $TestDrive 'standalone-output'
        $result = Invoke-Generator -Path $kokoroSpec -OutputPath $elsewhere -ManifestPath $script:psd1 -UpdateManifest
        $result.ManifestPath | Should -Be $script:psd1
        (Import-PowerShellDataFile -LiteralPath $script:psd1).FunctionsToExport | Should -Contain 'Test-KokoroHealth'
    }

    It 'does not list runtime helpers in the manifest' {
        $null = Invoke-Generator -Path $kokoroSpec -OutputPath (Join-Path $script:mod 'Source/Kokoro') -UpdateManifest
        (Import-PowerShellDataFile -LiteralPath $script:psd1).FunctionsToExport | Should -Not -Contain 'Invoke-KokoroApiRequest'
    }

    It 'replaces its region on regeneration with a smaller operation set' {
        $out = Join-Path $script:mod 'Source/Kokoro'
        $null = Invoke-Generator -Path $kokoroSpec -OutputPath $out -UpdateManifest
        $null = Invoke-Generator -Path $kokoroSpec -OutputPath $out -UpdateManifest -IncludePath '/health'
        $data = Import-PowerShellDataFile -LiteralPath $script:psd1
        $data.FunctionsToExport | Should -Contain 'Test-KokoroHealth'
        $data.FunctionsToExport | Should -Not -Contain 'New-KokoroSpeech'
        $data.FunctionsToExport | Should -Contain 'Get-Existing'
    }

    It 'throws when no manifest can be found' {
        $orphan = Join-Path $TestDrive 'orphan-drive/a/b'
        # Probe stops at the file-system root; use a path whose ancestors have no psd1.
        $null = New-Item -ItemType Directory -Path $orphan -Force
        $found = $false
        $probe = $orphan
        while ($probe) { if (Get-ChildItem -LiteralPath $probe -Filter *.psd1 -File -ErrorAction SilentlyContinue) { $found = $true }; $probe = Split-Path $probe -Parent }
        if ($found) { Set-ItResult -Skipped -Because 'an ancestor of the temp directory contains a manifest' }
        else { { New-OpenApiClient -Path $kokoroSpec -OutputPath $orphan -UpdateManifest 6>$null } | Should -Throw '*No .psd1*' }
    }

    It 'throws when several manifests are ambiguous' {
        Set-Content -LiteralPath (Join-Path $script:mod 'Second.psd1') -Value "@{ ModuleVersion = '1.0' }"
        { New-OpenApiClient -Path $kokoroSpec -OutputPath (Join-Path $script:mod 'Source/Kokoro') -UpdateManifest 6>$null } | Should -Throw '*Several manifests*'
    }
}
