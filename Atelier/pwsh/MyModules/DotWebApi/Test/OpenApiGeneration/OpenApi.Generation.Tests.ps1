BeforeDiscovery {
    $script:hasAnalyzer = [bool](Get-Module -ListAvailable -Name PSScriptAnalyzer)
}

BeforeAll {
    $moduleRoot = $PSScriptRoot | Split-Path -Parent | Split-Path -Parent
    Import-Module (Join-Path $moduleRoot 'DotWebApi.psd1') -Force
    $fixtures = Join-Path $PSScriptRoot 'Fixtures'
    $kokoroSpec = Join-Path $moduleRoot 'Source/Kokoro/kokoro_tts_openapi.json'
    $petSpec = Join-Path $fixtures 'petstore.v3.json'

    # Same arguments used to produce the committed Source/Kokoro/Kokoro.ps1 (see User-Guide).
    $kokoroArguments = @{
        Path            = $kokoroSpec
        DefaultEndpoint = 'http://192.168.1.103:8880'
        NameOverride    = @{
            'POST /dev/phonemize'              = 'ConvertTo-KokoroPhoneme'
            'POST /dev/generate_from_phonemes' = 'New-KokoroSpeechFromPhoneme'
        }
    }

    function Invoke-Generator
    {
        # Console summary goes to the information stream; keep the test output clean.
        New-OpenApiClient @args -PassThru 6>$null 3>$null
    }

    $script:generated = Join-Path $TestDrive 'generated'
    $script:kokoro = Invoke-Generator @kokoroArguments -OutputPath (Join-Path $script:generated 'kokoro')
    $script:pet = Invoke-Generator -Path $petSpec -OutputPath (Join-Path $script:generated 'pet')
}

Describe 'New-OpenApiClient output' {
    It 'writes the client and an embedded runtime outside the module' {
        $script:kokoro.RuntimeMode | Should -Be 'Embedded'
        $script:kokoro.ClientPath | Should -Exist
        $script:kokoro.RuntimePath | Should -Exist
        $script:kokoro.ClientPath | Should -BeLike '*Kokoro.ps1'
        (Split-Path $script:kokoro.RuntimePath -Parent) | Should -BeLike '*private'
    }

    It 'parses cleanly and defines every public function it reports' {
        $tokens = $null
        $errors = $null
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($script:kokoro.ClientPath, [ref]$tokens, [ref]$errors)
        $errors | Should -BeNullOrEmpty
        $defined = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $false).Name
        $script:kokoro.Function.Count | Should -Be 30 -Because '23 operations + 3 type constructors + 4 endpoint/credential helpers'
        foreach ($name in $script:kokoro.Function)
        {
            $name | Should -BeIn $defined
        }
    }

    It 'gives every function a synopsis and a description' {
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($script:kokoro.ClientPath, [ref]$null, [ref]$null)
        $functions = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $false)
        foreach ($function in $functions)
        {
            $help = $function.GetHelpContent()
            $help.Synopsis | Should -Not -BeNullOrEmpty -Because $function.Name
            $help.Description | Should -Not -BeNullOrEmpty -Because $function.Name
        }
    }

    It 'records the spec hash and name in a generated-file header' {
        $header = (Get-Content -LiteralPath $script:kokoro.ClientPath -TotalCount 8) -join "`n"
        $header | Should -Match '# <auto-generated>'
        $header | Should -Match 'kokoro_tts_openapi\.json - Kokoro TTS API 0\.9\.0'
        $header | Should -Match (Get-FileHash -LiteralPath $kokoroSpec -Algorithm SHA256).Hash.ToLowerInvariant()
    }

    It 'is byte-identical on regeneration and reports Unchanged' {
        $before = [System.IO.File]::ReadAllBytes($script:kokoro.ClientPath)
        $again = Invoke-Generator @kokoroArguments -OutputPath (Join-Path $script:generated 'kokoro')
        $again.State | Should -Be 'Unchanged'
        [System.IO.File]::ReadAllBytes($script:kokoro.ClientPath) | Should -Be $before
    }

    It 'uses LF endings and no BOM' {
        $bytes = [System.IO.File]::ReadAllBytes($script:kokoro.ClientPath)
        ($bytes[0..2] -join ',') | Should -Not -Be '239,187,191'
        [System.Text.Encoding]::UTF8.GetString($bytes) | Should -Not -Match "`r"
    }

    It 'matches the committed Source/Kokoro/Kokoro.ps1 (regenerate it when the generator changes)' {
        $copy = Join-Path $TestDrive 'drift'
        $null = Invoke-Generator @kokoroArguments -OutputPath $copy -RuntimeMode Module
        $committed = Join-Path $moduleRoot 'Source/Kokoro/Kokoro.ps1'
        # A Windows checkout with autocrlf may hold CRLF; the generator always writes LF.
        $regenerated = (Get-Content -LiteralPath (Join-Path $copy 'Kokoro.ps1') -Raw) -replace "`r`n", "`n"
        $regenerated | Should -BeExactly ((Get-Content -LiteralPath $committed -Raw) -replace "`r`n", "`n")
    }

    It 'is clean under the repository PSScriptAnalyzer settings' -Skip:(-not $script:hasAnalyzer) {
        $settings = Join-Path $moduleRoot '../../PSScriptAnalyzerSettings.psd1'
        foreach ($file in $script:kokoro.ClientPath, $script:kokoro.RuntimePath, $script:pet.ClientPath)
        {
            $params = if (Test-Path $settings) { @{ Settings = $settings } } else { @{ Severity = 'Error' } }
            Invoke-ScriptAnalyzer -Path $file @params | Should -BeNullOrEmpty -Because $file
        }
    }
}

Describe 'New-OpenApiClient naming of the Kokoro API' {
    It 'creates the expected function names' {
        $expected = 'New-KokoroSpeech', 'New-KokoroCaptionedSpeech', 'New-KokoroDialogue', 'Get-KokoroModel', 'Get-KokoroModelById',
        'Get-KokoroVoice', 'Join-KokoroVoice', 'Save-KokoroAudioFile', 'Test-KokoroHealth', 'Test-KokoroEndpoint',
